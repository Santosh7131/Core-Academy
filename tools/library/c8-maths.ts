const hyp = Math.hypot;
const isSquare = (n: number) => Number.isInteger(Math.sqrt(n));
const ROMAN: Record<string, number> = { I: 1, V: 5, X: 10, L: 50, C: 100, D: 500, M: 1000 };
/** Value of a Roman numeral, a smaller symbol before a larger one being subtracted. */
const roman = (s: string) => [...s].reduce((sum, ch, i) => {
  const v = ROMAN[ch];
  return ROMAN[s[i + 1]] > v ? sum - v : sum + v;
}, 0);
const firstWith = (ok: (n: number) => boolean, from = 1) => {
  let n = from;
  while (!ok(n)) n++;
  return n;
};

