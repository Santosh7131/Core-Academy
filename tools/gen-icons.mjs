// Generates lib/ui/icons.dart for the app and the admin app: Phosphor Light icons (MIT) as plain
// IconData on a bundled font. phosphor_flutter 2.1.0 subclasses IconData, which is a final class
// on Flutter 3.47, so the package cannot compile; its font and codepoints are still right.
// Run from the project root:
//   node tools/gen-icons.mjs
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const pkg = join(process.env.LOCALAPPDATA, 'Pub', 'Cache', 'hosted', 'pub.dev', 'phosphor_flutter-2.1.0');
const src = readFileSync(join(pkg, 'lib', 'src', 'phosphor_icons_light.dart'), 'utf8');

