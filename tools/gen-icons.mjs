function write(target, list, fontDir) {
  const lines = list.map((n) => {
    const m = src.match(new RegExp(`static const ${n} = PhosphorFlatIconData\\((0x[0-9a-f]+), 'Light'\\);`));
    if (!m) throw new Error(`icon not found: ${n}`);
    return `  static const ${n} = IconData(${m[1]}, fontFamily: _family);`;
  });
  writeFileSync(
    target,
    `// Generated by tools/gen-icons.mjs. Phosphor Light icons (MIT licence, assets/fonts/PHOSPHOR-LICENSE.txt).
import 'package:flutter/widgets.dart';

/// Thin-stroke icons (the guide bans 2px default sets).
abstract final class Ph {
  static const _family = 'PhosphorLight';

${lines.join('\n')}
}
`,
  );
  copyFileSync(join(pkg, 'lib', 'fonts', 'Phosphor-Light.ttf'), join(fontDir, 'PhosphorLight.ttf'));
  copyFileSync(join(pkg, 'LICENSE'), join(fontDir, 'PHOSPHOR-LICENSE.txt'));
  console.log(`${target}: ${list.length} icons; font and licence copied`);
}

write('app/lib/ui/icons.dart', names, 'app/assets/fonts');
// The admin app shares the main app's components, so it needs every icon they use, plus its own.
write('admin/lib/ui/icons.dart', [...new Set([...names, ...admin])], 'admin/assets/fonts');
